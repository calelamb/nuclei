"""Dense fallback for the DLA when fixed gates are non-Clifford (``n <= DENSE_MAX_QUBITS``).

Effective generators are ``G~_k = V_k† G_k V_k`` with ``V_k`` the (dense) product of *all* fixed
gates before rotation ``k`` (fixed gates are pushed to the end).  The closure is a budgeted
Gram-Schmidt over the real vector space of Hermitian matrices (vectorised as ``[Re; Im]``),
bracketing every new element with the generators (same Jacobi argument as the string path).
"""

from __future__ import annotations

import time
from typing import Callable, Sequence

import numpy as np

from kernel.trainability._circuit_walk import FixedClifford, FixedOther, Item, Rotation
from kernel.trainability.gates import GATE_SPECS
from kernel.trainability.pauli import PauliSum, PauliTerm, pauli_sum_matrix

DENSE_MAX_QUBITS = 6


def _embed(matrix: np.ndarray, qubits: tuple[int, ...], n: int) -> np.ndarray:
    """The ``2^n x 2^n`` operator of a gate acting on ``qubits`` (qubit q = bit q)."""
    k, dim = len(qubits), 1 << n
    axes = [n - 1 - q for q in reversed(qubits)]
    state = np.eye(dim, dtype=np.complex128).reshape((2,) * n + (dim,))
    gate = matrix.reshape((2,) * (2 * k))
    out = np.tensordot(gate, state, axes=(list(range(k, 2 * k)), axes))
    out = np.moveaxis(out, list(range(k)), axes)
    return out.reshape(dim, dim)


def _fixed_matrix(item: FixedClifford | FixedOther) -> np.ndarray:
    spec = GATE_SPECS[item.gate_name]
    if isinstance(item, FixedOther):
        return spec.matrix(item.angles)
    if spec.n_angles == 0:
        return spec.matrix(())
    # a constant quarter-turn rotation: rebuild the exact gate from its decomposition
    mat = np.eye(1 << len(item.qubits), dtype=np.complex128)
    for name in item.names:
        mat = GATE_SPECS[name].matrix(()) @ mat
    return mat


def effective_generators_dense(items: Sequence[Item], n: int) -> list[tuple[str, np.ndarray]]:
    """``[(parameter name, G~)]`` with shared parameters summed (``a * G~`` per rotation)."""
    dim = 1 << n
    v = np.eye(dim, dtype=np.complex128)
    acc: dict[str, np.ndarray] = {}
    for item in items:
        if isinstance(item, Rotation):
            g = pauli_sum_matrix(PauliSum(tuple(PauliTerm(c, ops) for c, ops in item.terms)), n)
            eff = item.ref.coeff * (v.conj().T @ g @ v)
            acc[item.ref.name] = acc.get(item.ref.name, 0) + eff
        else:
            v = _embed(_fixed_matrix(item), item.qubits, n) @ v
    return list(acc.items())


def dense_closure_budgeted(
    mats: Sequence[np.ndarray], *, max_dimension: int, time_budget_s: float,
    cancel: Callable[[], bool] | None = None, tol: float = 1e-9,
) -> dict:
    """Dimension of the real Lie algebra generated by ``i * mats`` (Hermitian ``mats``)."""
    t0 = time.perf_counter()
    deadline = t0 + time_budget_s
    gens = []
    for m in mats:
        m = 1j * (m - np.trace(m) / m.shape[0] * np.eye(m.shape[0]))  # traceless part (identity is central)
        nrm = np.linalg.norm(m)
        if nrm > 1e-12:
            gens.append(m / nrm)
    size = 2 * (mats[0].size if len(mats) else 0)
    basis = np.zeros((64, size))
    count, queue, reason = 0, [], None

    def add(m: np.ndarray, scale: float) -> bool:
        nonlocal count, basis
        v = np.concatenate([m.real.ravel(), m.imag.ravel()])
        for _ in range(2):
            if count:
                v = v - basis[:count].T @ (basis[:count] @ v)
        nv = np.linalg.norm(v)
        if nv <= tol * scale:
            return False
        if count == basis.shape[0]:
            basis = np.vstack([basis, np.zeros_like(basis)])
        basis[count] = v / nv
        count += 1
        queue.append(m / np.linalg.norm(m))
        return True

    for g in gens:
        add(g, 1.0)
    head = 0
    while reason is None and head < len(queue):
        e = queue[head]
        head += 1
        for g in gens:
            if cancel is not None and cancel():
                reason = "cancelled"
            elif time.perf_counter() > deadline:
                reason = "time_budget"
            elif count >= max_dimension:
                reason = "max_dimension"
            if reason:
                break
            add(g @ e - e @ g, 2.0)
    return {"status": "complete" if reason is None else "truncated", "dimension": count,
            "dimension_lower_bound": count, "reason": reason, "elapsed_ms": (time.perf_counter() - t0) * 1e3}
