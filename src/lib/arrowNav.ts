/**
 * Target index for a roving-focus key press (Arrow keys wrap, Home/End jump),
 * or null when the key is not a navigation key. Shared by radio groups and tabs.
 */
export function arrowNavTarget(key: string, current: number, count: number): number | null {
  if (count <= 0) return null;
  switch (key) {
    case 'ArrowRight':
    case 'ArrowDown':
      return (current + 1) % count;
    case 'ArrowLeft':
    case 'ArrowUp':
      return (current - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
