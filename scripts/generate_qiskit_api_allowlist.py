"""Regenerate src/platform/pyodide/shim/_qiskit_api.py from a real Qiskit install.

Run with a Python that has real qiskit (+ qiskit_aer, qiskit_ibm_runtime) installed:
    python scripts/generate_qiskit_api_allowlist.py
The browser shim uses the result to tell a real Qiskit name it does not implement
("not in the browser subset") from a typo ("Did you mean ...?").
"""

import importlib
import pkgutil
from pathlib import Path

MODULES = [
    "qiskit", "qiskit.circuit", "qiskit.circuit.library", "qiskit.quantum_info",
    "qiskit.transpiler", "qiskit.transpiler.preset_passmanagers", "qiskit.providers",
    "qiskit.providers.fake_provider", "qiskit.visualization", "qiskit.synthesis",
    "qiskit.pulse", "qiskit.primitives", "qiskit.algorithms", "qiskit_aer",
    "qiskit_aer.noise", "qiskit_ibm_runtime", "qiskit_addon_cutting",
]
OUT = Path(__file__).resolve().parents[1] / "src/platform/pyodide/shim/_qiskit_api.py"


def public_names(module):
    names = {n for n in dir(module) if not n.startswith("_")}
    path = getattr(module, "__path__", None)
    if path:
        names |= {m.name for m in pkgutil.iter_modules(path)}
    return sorted(names)


def fmt(names):
    body = "\n".join(f'    "{n}",' for n in names)
    return f"frozenset({{\n{body}\n}})"


def main():
    from qiskit import QuantumCircuit

    parts = [
        '"""Generated by scripts/generate_qiskit_api_allowlist.py - do not edit by hand.\n\n'
        "Public names of real Qiskit, used to separate typos from browser-subset limits.\n"
        '"""\n\n'
    ]
    methods = public_names(QuantumCircuit)
    parts.append(f"QUANTUM_CIRCUIT_API = {fmt(methods)}\n\nMODULE_API = {{\n")
    for name in MODULES:
        try:
            module = importlib.import_module(name)
        except ImportError:
            continue
        parts.append(f'    "{name}": {fmt(public_names(module))},\n')
    parts.append("}\n")
    OUT.write_text("".join(parts))


if __name__ == "__main__":
    main()
